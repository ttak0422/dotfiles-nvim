local ok, err = pcall(function()
  local bundle = assert(vim.env.V3_BUNDLE)
  assert(vim.env.NVIM_APPNAME == "nvim-v3-default")
  assert(vim.tbl_contains(vim.v.argv, bundle .. "/init.lua"))
  assert(package.loaded.divine, "divine runtime was not initialized")
  assert(vim.v.errmsg == "", vim.v.errmsg)
  local plan = dofile(bundle .. "/plan.lua")
  assert(next(plan.nodes) == nil, "unexpected plugins")
  assert(next(plan.units) == nil, "unexpected dependency units")
  assert(next(plan.startup_units) == nil, "unexpected startup units")
  assert(plan.startup == nil, "unexpected startup configuration")
end)
if not ok then
  io.stderr:write(tostring(err) .. "\n")
  vim.cmd("cquit 1")
end
