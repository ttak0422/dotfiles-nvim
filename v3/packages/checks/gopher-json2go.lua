-- These dependencies must come from the bundle, without GoInstallDeps.
for _, command in ipairs({ "go", "gomodifytags", "impl", "iferr", "gotests", "json2go" }) do
  assert(vim.fn.executable(command) == 1, command .. " is missing from the profile")
end

local function reset()
  vim.cmd.enew({ bang = true })
  vim.bo.filetype = "go"
  vim.api.nvim_buf_set_lines(0, 0, -1, false, { "package example", "" })
  vim.api.nvim_win_set_cursor(0, { 2, 0 })
  return vim.api.nvim_get_current_buf()
end
local function expect_struct(buf, name, fields)
  local text = table.concat(vim.api.nvim_buf_get_lines(buf, 0, -1, false), "\n")
  assert(text:find("type " .. name .. " struct {", 1, true), text)
  for _, field in ipairs(fields) do
    assert(text:find(field, 1, true), "missing " .. field .. ": " .. text)
  end
  -- Confirm the generated declaration is valid Go source.
  local result = vim.system({ "gofmt" }, { stdin = text, text = true }):wait()
  assert(result.code == 0, result.stderr)
end

local original = reset()
vim.cmd([[GoJson {"name":"Alice","active":true}]])
expect_struct(original, "AutoGenerated", { "Name string", '`json:"name"`', "Active bool", '`json:"active"`' })

-- Exercise the normal scratch-buffer / :write command flow as well.
original = reset()
local config = require("gopher.config")
config.json2go.type_name = "Person"
vim.cmd.GoJson()
local input = vim.api.nvim_get_current_buf()
assert(input ~= original and vim.bo.buftype == "acwrite")
vim.cmd.stopinsert()
vim.api.nvim_buf_set_lines(input, 0, -1, false, {
  "// JSON input",
  '{"name":"Bob","active":false}',
})
vim.cmd.write()
assert(
  vim.wait(3000, function()
    return not vim.api.nvim_buf_is_valid(input)
  end, 20),
  "GoJson input did not close after write"
)
assert(vim.api.nvim_get_current_buf() == original, "GoJson did not restore the original buffer")
expect_struct(original, "Person", { "Name string", '`json:"name"`', "Active bool", '`json:"active"`' })
config.json2go.type_name = nil

vim.cmd("checkhealth gopher")
local health = table.concat(vim.api.nvim_buf_get_lines(0, 0, -1, false), "\n")
assert(not health:find("ERROR", 1, true), health)
assert(health:find("json2go is found", 1, true), health)
assert(health:find("`go` parser is installed", 1, true), health)
assert(vim.v.errmsg == "", vim.v.errmsg)
